def translate(en: str) -> str:
    placeholders: dict[str, str] = {}

    def save(m: re.Match[str]) -> str:
        key = f"__PH{len(placeholders)}__"
        placeholders[key] = m.group(0)
        return key

    s = re.sub(r"\{\{[^}]+\}\}", save, en)
    for a, b in phrase_pairs:
        s = s.replace(a, b)
    for key, value in placeholders.items():
        s = s.replace(key, value)
    return s


def main() -> None:
    for ns in ["inventory", "purchasing", "costing", "accounting", "settings"]:
        en = json.loads((base / "en" / f"{ns}.json").read_text())
        th = {k: translate(v) for k, v in en.items()}
        leftover = [
            k
            for k, v in th.items()
            if v == en[k] and re.search(r"[A-Za-z]{4,}", v)
        ]
        (base / "th" / f"{ns}.json").write_text(
            json.dumps(th, ensure_ascii=False, indent=2) + "\n"
        )
        print(ns, "keys", len(th), "unchanged", len(leftover))
        for k in leftover[:12]:
            print(" ", k, "=", en[k])


if __name__ == "__main__":
    main()
